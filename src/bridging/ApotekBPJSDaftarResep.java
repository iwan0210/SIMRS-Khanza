    private void tampil() {
        try {
            headers = new HttpHeaders();
            headers.setContentType(MediaType.APPLICATION_FORM_URLENCODED);
            headers.add("x-cons-id", koneksiDB.CONSIDAPIAPOTEKBPJS());
            utc = String.valueOf(api.GetUTCdatetimeAsString());
            headers.add("x-timestamp", utc);
            headers.add("x-signature", api.getHmac(utc));
            headers.add("user_key", koneksiDB.USERKEYAPIAPOTEKBPJS());
            String tglAwal = Valid.SetTgl(DTPCari1.getSelectedItem().toString());
            String tglAkhir = Valid.SetTgl(DTPCari2.getSelectedItem().toString());
            requestJson = "{"
                    + "\"kdppk\":\"0174A011\","
                    + "\"KdJnsObat\":\"" + JenisObat.getSelectedIndex() + "\","
                    + "\"JnsTgl\":\"" + getJenisTanggalValue(JenisTanggal.getSelectedIndex()) + "\","
                    + "\"TglMulai\":\"" + tglAwal + " 00:00:00\","
                    + "\"TglAkhir\":\"" + tglAkhir + " 23:59:59\""
                    + "}";
            requestEntity = new HttpEntity(requestJson, headers);
            URL = link + "/daftarresep";
            System.out.println(URL);
            root = mapper.readTree(api.getRest().exchange(URL, HttpMethod.POST, requestEntity, String.class).getBody());
            nameNode = root.path("metaData");
            if (nameNode.path("code").asText().equals("200")) {
                Valid.tabelKosong(tabMode);
                response = mapper.readTree(api.Decrypt(root.path("response").asText(), utc));
                if (response.isArray()) {
                    for (JsonNode list : response) {
                        tabMode.addRow(new Object[]{
                            list.path("NORESEP").asText(),list.path("NOAPOTIK").asText(),list.path("NOSEP_KUNJUNGAN").asText(),
                            list.path("NOKARTU").asText(),list.path("NAMA").asText(),list.path("TGLENTRY").asText(),
                            list.path("TGLRESEP").asText(),list.path("TGLPELRSP").asText(),list.path("BYTAGRSP").asText(),
                            list.path("BYVERRSP").asText(),getJenisResepValue(list.path("KDJNSOBAT").asText()),
                            list.path("FASKESASAL").asText(),list.path("FLAGITER").asText()
                        });
                    }
                }
            } else {
                JOptionPane.showMessageDialog(null, nameNode.path("message").asText());
            }
        } catch (Exception ex) {
            System.out.println("Notifikasi : " + ex);
            if (ex.toString().contains("UnknownHostException")) {
                JOptionPane.showMessageDialog(rootPane, "Koneksi ke server BPJS terputus...!");
            }
        }
    }

