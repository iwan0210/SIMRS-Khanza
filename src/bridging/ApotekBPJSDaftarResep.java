    private void runBackground(Runnable task) {
        if (ceksukses) {
            return;
        }
        if (executor.isShutdown() || executor.isTerminated()) {
            return;
        }
        if (!isDisplayable()) {
            return;
        }

        ceksukses = true;
        setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));

        try {
            executor.submit(() -> {
                try {
                    task.run();
                } finally {
                    ceksukses = false;
                    SwingUtilities.invokeLater(() -> {
                        if (isDisplayable()) {
                            setCursor(Cursor.getDefaultCursor());
                        }
                    });
                }
            });
        } catch (RejectedExecutionException ex) {
            ceksukses = false;
        }
    }

    @Override
    public void dispose() {
        executor.shutdownNow();
        super.dispose();
    }
    
    private String getJenisTanggalValue(int n) {
        if (n == 0) {
            return "TGLPELSJP";
        }
        
        return "TGLRSP";
    }
    
    private String getJenisResepValue(String n) {
        String value = "";
        switch (n) {
            case "1":
                value = "1. Obat PRB";
                break;
            case "2":
                value = "2. Obat Kronis Belum Stabil";
                break;
            case "3":
                value = "3. Obat Kemoterapi";
                break;
            default:
                break;
        }
        
        return value;
    }
