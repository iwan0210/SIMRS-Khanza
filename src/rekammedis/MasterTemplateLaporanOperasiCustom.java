    private void tampil() {
        Valid.tabelKosong(tabMode);
        try {
            ps = koneksi.prepareStatement(
                    "select * from template_laporan_operasi_custom "
                    + "where (no_template like ? or nama_operasi like ? or "
                    + "laporan_operasi like ? or macam_operasi like ?) "
                    + "order by no_template");
            try {
                ps.setString(1, "%" + TCari.getText().trim() + "%");
                ps.setString(2, "%" + TCari.getText().trim() + "%");
                ps.setString(3, "%" + TCari.getText().trim() + "%");
                ps.setString(4, "%" + TCari.getText().trim() + "%");
                rs = ps.executeQuery();
                while (rs.next()) {
                    tabMode.addRow(new Object[]{
                        rs.getString("no_template"), rs.getString("nama_operasi"), rs.getString("jaringan_dieksisi"), rs.getString("permintaan_pa"),
                        rs.getString("diagnosa_preop"), rs.getString("diagnosa_postop"), rs.getString("macam_operasi"), rs.getString("instruksi_pasca_operasi"),
                        rs.getString("laporan_operasi")
                    });
                }
            } catch (Exception e) {
                System.out.println(e);
            } finally {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
            }
        } catch (Exception e) {
            System.out.println("Notifikasi : " + e);
        }
        LCount.setText("" + tabMode.getRowCount());
    }

